using System;
using System.Security;

namespace StackIt.Client
{
    /// <summary>
    /// Builds the platform deep-link declarations from the single public base URL, so switching to
    /// a custom domain only means changing AppConfig.apiBaseUrl (and PUBLIC_BASE_URL on the server).
    /// </summary>
    public static class DeepLinkManifest
    {
        public static string Host(string baseUrl) => new Uri(baseUrl.Trim()).Host;

        /// <summary>
        /// Manifest of Assets/Plugins/Android/StackItManifest.androidlib. Gradle merges the activity
        /// entry into Unity's own activity (same android:name), adding the intent filters.
        /// </summary>
        public static string AndroidLibraryManifest(string baseUrl, string scheme, string activityName)
        {
            string host = SecurityElement.Escape(Host(baseUrl));
            string safeScheme = SecurityElement.Escape(scheme.ToLowerInvariant());
            string activity = SecurityElement.Escape(activityName);
            return $@"<?xml version=""1.0"" encoding=""utf-8""?>
<!-- GENERATED by Stack IT build hooks from AppConfig before each Android build. Do not edit. -->
<manifest xmlns:android=""http://schemas.android.com/apk/res/android"" package=""com.stackit.nativeplugin.manifest"">
    <application>
        <activity android:name=""{activity}"" android:exported=""true"">
            <!-- App Links: https://{host}/c/CODE opens the app (verified via /.well-known/assetlinks.json). -->
            <intent-filter android:autoVerify=""true"">
                <action android:name=""android.intent.action.VIEW"" />
                <category android:name=""android.intent.category.DEFAULT"" />
                <category android:name=""android.intent.category.BROWSABLE"" />
                <data android:scheme=""https"" android:host=""{host}"" android:pathPrefix=""/c/"" />
            </intent-filter>
            <!-- ""Open in app"" button on the landing page: {safeScheme}://c/CODE -->
            <intent-filter>
                <action android:name=""android.intent.action.VIEW"" />
                <category android:name=""android.intent.category.DEFAULT"" />
                <category android:name=""android.intent.category.BROWSABLE"" />
                <data android:scheme=""{safeScheme}"" android:host=""c"" />
            </intent-filter>
        </activity>
        <provider
            android:name=""androidx.core.content.FileProvider""
            android:authorities=""${{applicationId}}.stackit.fileprovider""
            android:exported=""false""
            android:grantUriPermissions=""true"">
            <meta-data android:name=""android.support.FILE_PROVIDER_PATHS"" android:resource=""@xml/stackit_file_paths"" />
        </provider>
    </application>
</manifest>
";
        }
    }
}
